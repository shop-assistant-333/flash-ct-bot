package dev.lowkkid.tools.qparser.sql;

import dev.lowkkid.tools.qparser.model.Harvest;
import dev.lowkkid.tools.qparser.model.HarvestedOption;
import dev.lowkkid.tools.qparser.model.HarvestedQuestion;
import dev.lowkkid.tools.qparser.model.QuestionType;

import java.util.StringJoiner;

/**
 * The one place that knows the database schema. Every adapter feeds it the same
 * {@link Harvest} shape, so a new source site never touches this file.
 */
public final class SqlGenerator {

    private SqlGenerator() {
    }

    public static String generate(Harvest harvest) {
        StringBuilder sql = new StringBuilder();
        sql.append("-- Generated by tools/qparser from ").append(harvest.getSource()).append('\n');
        sql.append("-- Harvested at ").append(harvest.getHarvestedAt()).append('\n');
        sql.append("-- ").append(harvest.getQuestions().size()).append(" question(s), ");
        sql.append(harvest.getLessonId() != null
                ? "lesson_id = " + harvest.getLessonId()
                : "practice questions of subject_id = " + harvest.getSubjectId());
        sql.append("\n\nBEGIN;\n");

        int order = harvest.getStartOrder();
        for (HarvestedQuestion question : harvest.getQuestions()) {
            sql.append('\n');
            appendQuestion(sql, harvest, question, harvest.getLessonId() != null ? order++ : null);
        }

        sql.append("\nCOMMIT;\n");
        return sql.toString();
    }

    private static void appendQuestion(StringBuilder sql,
                                       Harvest harvest,
                                       HarvestedQuestion question,
                                       Integer order) {
        sql.append("-- ").append(oneLineComment(question.getTitle())).append('\n');

        String values = new StringJoiner(", ", "(", ")")
                .add(literal(question.getTitle()))
                .add(literal(question.getType().name()) + "::question_type")
                .add(order == null ? "NULL" : String.valueOf(order))
                .add(number(harvest.getLessonId()))
                .add(number(harvest.getSubjectId()))
                .add(literal(question.getCorrectAnswer()))
                .add(literal(question.getExplanation()))
                .toString();

        String columns = "(title, type, \"order\", lesson_id, subject_id, correct_answer, explanation)";

        if (question.getOptions().isEmpty()) {
            sql.append("INSERT INTO questions ").append(columns).append('\n')
                    .append("VALUES ").append(values).append(";\n");
            return;
        }

        // The options need the id the insert just produced, so both statements go in one CTE.
        sql.append("WITH q AS (\n")
                .append("    INSERT INTO questions ").append(columns).append('\n')
                .append("    VALUES ").append(values).append('\n')
                .append("    RETURNING id\n")
                .append(")\n")
                .append("INSERT INTO answer_options (question_id, text, is_correct)\n")
                .append("SELECT q.id, v.text, v.is_correct FROM q, (VALUES\n");

        StringJoiner rows = new StringJoiner(",\n");
        for (HarvestedOption option : question.getOptions()) {
            rows.add("    (" + literal(option.getText()) + ", " + (option.isCorrect() ? "TRUE" : "FALSE") + ")");
        }
        sql.append(rows).append("\n) AS v(text, is_correct);\n");
    }

    private static String number(Integer value) {
        return value == null ? "NULL" : String.valueOf(value);
    }

    private static String literal(String value) {
        if (value == null) {
            return "NULL";
        }
        return "'" + value.replace("\r", "").replace("'", "''") + "'";
    }

    private static String oneLineComment(String title) {
        if (title == null) {
            return "(no title)";
        }
        String flat = title.replaceAll("\\s+", " ").trim();
        return flat.length() <= 90 ? flat : flat.substring(0, 87) + "...";
    }

    /** Guards against a harvest that the schema would reject. */
    public static void validate(Harvest harvest) {
        if ((harvest.getLessonId() == null) == (harvest.getSubjectId() == null)) {
            throw new IllegalArgumentException(
                    "Exactly one of lessonId / subjectId must be set (questions_owner_check).");
        }
        for (HarvestedQuestion question : harvest.getQuestions()) {
            if (question.getType() == QuestionType.INPUT && !question.getOptions().isEmpty()) {
                throw new IllegalArgumentException(
                        "Question " + question.getSourceId() + " is INPUT but carries options.");
            }
            if (!question.isComplete()) {
                throw new IllegalArgumentException(
                        "Question " + question.getSourceId() + " has no correct answer.");
            }
        }
    }
}
